/**
 * Fetch Rinus "Voetbal echt" ball ratings and merge them into rinusMetaMap.js.
 * Run: node scripts/sync-rinus-reality.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { RINUS_ID_MAP } from '../src/data/rinusLinks.js'
import { EXERCISES } from '../src/data/exercises.js'
import { RINUS_META_BY_RINUS_ID, RINUS_META_MAP } from '../src/data/rinusMetaMap.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const metaOut = path.join(__dirname, '../src/data/rinusMetaMap.js')

function parseRealityRating(entry) {
  const ratings = entry?.exerciseContent?.[0]?.exerciseRatings
  if (!Array.isArray(ratings)) return null
  const reality = ratings.find(r => r?.ratingType === 'exerciseReality')
  const n = Number.parseInt(reality?.rating, 10)
  return Number.isInteger(n) && n >= 1 && n <= 5 ? n : null
}

async function fetchRealityRating(rinusId) {
  const res = await fetch(`https://rinus.knvb.nl/nl/exercise/id/${rinusId}`)
  if (!res.ok) return null
  const html = await res.text()
  const nextMatch = html.match(/<script id="__NEXT_DATA__"[^>]*>([\s\S]*?)<\/script>/)
  if (!nextMatch) return null
  const entry = JSON.parse(nextMatch[1])?.props?.pageProps?.entry
  return parseRealityRating(entry)
}

const uniqueIds = [...new Set([
  ...Object.values(RINUS_ID_MAP),
  ...EXERCISES.map(ex => ex.rinusId).filter(Boolean),
])]

const realityByRinusId = {}
for (const id of uniqueIds) {
  process.stdout.write(`Fetching ${id}... `)
  const rating = await fetchRealityRating(id)
  realityByRinusId[id] = rating
  console.log(rating == null ? 'missing' : `${rating} balls`)
  await new Promise(r => setTimeout(r, 120))
}

function withReality(meta, rinusId) {
  if (!meta) return meta
  const footballReality = rinusId ? (realityByRinusId[rinusId] ?? null) : null
  return { ...meta, footballReality }
}

const metaByRinusId = {}
for (const [id, meta] of Object.entries(RINUS_META_BY_RINUS_ID)) {
  metaByRinusId[id] = withReality(meta, id)
}

const metaMap = {}
for (const [exId, meta] of Object.entries(RINUS_META_MAP)) {
  const rinusId = EXERCISES.find(ex => ex.id === exId)?.rinusId ?? RINUS_ID_MAP[exId]
  metaMap[exId] = withReality(meta, rinusId)
}

fs.writeFileSync(metaOut, `/**
 * Rinus display metadata (title, description, dimensions, …).
 * Generated by scripts/sync-rinus-content.mjs
 */
export const RINUS_META_BY_RINUS_ID = ${JSON.stringify(metaByRinusId, null, 2)}

export const RINUS_META_MAP = ${JSON.stringify(metaMap, null, 2)}
`)

const known = Object.values(realityByRinusId).filter(n => n != null).length
console.log(`Wrote ${metaOut} (${known}/${uniqueIds.length} with footballReality)`)
